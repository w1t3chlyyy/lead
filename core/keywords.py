"""Дешёвый префильтр до вызова Qwen: нужны И намерение, И тема, и нет маркеров продавца."""
from __future__ import annotations

import re

INTENT = re.compile(
    r"(мне\s+нужн\w*|нужн[аоы]?\b|ищу|ищем\s+(?:кто|исполнител|дизайн|разработ)\w*|требу\w+|"
    r"посоветуйте|порекомендуйте|подскажите|кто\s+(?:сделает|может|умеет|занимается|возьм\w+|берет\w*|делает)|"
    r"сделайте|закажу|хочу\s+заказать|куплю|хочу\s+купить|где\s+(?:заказать|купить|найти)|"
    r"как\s+(?:купить|заказать)|нужна\s+помощь|надо\s+сделать|нужно\s+сделать)",
    re.I,
)

# Тематика твоих товаров и услуг. Дополняй под свой каталог.
TOPIC = re.compile(
    r"(бот\w*|чат-?бот\w*|дизайн\w*|дизайнер\w*|сайт\w*|лендинг\w*|аватарк\w*|баннер\w*|логотип\w*|"
    r"\bлого\b|оформлен\w*|упаковк\w*|брендинг\w*|превью|обложк\w*|парсер\w*|автоматизац\w*|"
    r"(?:ai|ии|ai-|ии-)\s*агент\w*|нейросет\w*|звезд\w*|stars|премиум\w*|premium|nft|подарк\w*|"
    r"юзернейм\w*|username|верификац\w*|накрутк\w*|мини-?апп\w*|mini\s?app|разработчик\w*|программист\w*|"
    r"верстк\w*|таргет\w*|смм|smm|монтаж\w*|ава\b|шапк\w*)",
    re.I,
)

# Так пишут продавцы/исполнители, а не заказчики
SELLER = re.compile(
    r"(предлагаю|делаю\s+на\s+заказ|оказываю|мои\s+услуги|наши\s+услуги|портфолио|беру\s+заказы|"
    r"принимаю\s+заказы|открыт\s+набор|прайс|скидк\w+\s+\d|пишите\s+в\s+(?:лс|личку)|в\s+наличии|"
    r"акци[яи]\b|подписывайтесь)",
    re.I,
)

MIN_LEN, MAX_LEN = 12, 900


def quick_filter(text: str) -> bool:
    if not text or not (MIN_LEN <= len(text) <= MAX_LEN):
        return False
    if SELLER.search(text):
        return False
    return bool(INTENT.search(text) and TOPIC.search(text))


